/**
 * Living units (PROJECT.md §3, §4; chunk 03). Shared between offense and defense, but each
 * type carries TWO distinct ratings: `offense` governs it in a standing raid party,
 * `defense` governs it when posted in a wagon circle. They are authored independently —
 * the best raider is deliberately not the best guard — and a test asserts the roster has no
 * fixed ratio between them.
 *
 * Region-locked and mechanically distinct: every region's roster is its own stat blocks,
 * affinity mix and aggro/leash profile, not a reskin. A test asserts no two unit types
 * share a stat block.
 *
 * Units: distances in Fixed cells, speeds in Fixed cells/second, cooldowns in ms. Ratings
 * and HP are plain integers. Range alone decides melee vs. ranged. Every value is TUNABLE
 * and authored within the bounds in TUNABLES (tests check the bounds).
 *
 * Reference defaults: where a value IS the registry default (TUNABLES.PER_TYPE_OVERRIDABLE_
 * DEFAULTS — the healers' radius / fraction / charges / cooldown today), the unit references
 * the TUNABLES key instead of re-authoring the literal, so re-tuning the default re-tunes
 * every type that did not deliberately deviate. A test enforces this on the healers.
 *
 * The four healers are deliberately four different CHASSIS around the same archetype
 * (chunk 03 QA S4): a fast melee water-runner (desert), a mounted circuit rider that rides
 * out to the wounded (high plains, Beast), a slow wide-radius stationary dispenser
 * (mountain), and a ranged, Powder-affinity bottle-thrower (badlands). A test asserts every
 * unit's nearest cross-region neighbour is at a normalised stat distance of at least 0.10.
 *
 * Theming: settlers, outlaws, frontier industry and animals only. No Indigenous
 * characters or culture — PROJECT.md §20 requires dedicated research before any such
 * content is authored, and that is out of this chunk's scope.
 */
import type { Ability } from "./abilities.js";
import type { AffinityCategory } from "./affinity.js";
import { fp, fpMilli, ms, seconds, type Fixed, type Millis } from "./fixedPoint.js";
import { deepFreeze } from "./freeze.js";
import type { RegionId } from "./regions.js";
import { TUNABLES } from "./tunables.js";

export interface LivingUnitType {
  readonly id: `${RegionId}.${string}`;
  readonly regionId: RegionId;
  readonly displayName: string;
  readonly flavor: string;
  readonly affinity: AffinityCategory;
  /** Rating used when this unit fights in a standing raid party. */
  readonly offense: number;
  /** Rating used when this unit is posted in a wagon circle. Independent of `offense`. */
  readonly defense: number;
  /** Max HP at merge level 1. */
  readonly hp: number;
  /** Cells per second. */
  readonly moveSpeed: Fixed;
  /** Cells. ≈1.0 is melee; ≥2.5 reads as ranged. No separate flag. */
  readonly attackRange: Fixed;
  /** Time between hits. One hit = the damage formula once. */
  readonly attackCooldown: Millis;
  /** Posted only: how close an attacker must come to be noticed. Cells. */
  readonly aggroRadius: Fixed;
  /** Posted only: how far it chases from its post before returning. Cells. */
  readonly leashDistance: Fixed;
  /** Exactly one. */
  readonly ability: Ability;
}

/**
 * Balance pass 5 (BALANCE-LOG.md): every unit's posted engagement — its aggro radius and its leash —
 * carries TUNABLES.POST_ENGAGEMENT_BONUS on top of the authored value, so a post answers a ranged
 * raider shooting from outside the fence instead of standing idle. One number, every type: the
 * authored literals below stay the per-type profile (and its distinctness), the bonus is the dial.
 * Posted-only fields: a raider never reads aggro or leash.
 */
const engage = (v: Fixed): Fixed => (v + TUNABLES.POST_ENGAGEMENT_BONUS) as Fixed;

