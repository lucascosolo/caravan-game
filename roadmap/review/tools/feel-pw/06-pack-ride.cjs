const { open, snap, dump, save, sleep, BASE, OUT } = require("./lib.cjs");
const { panels } = require("./lib2.cjs");
const STATE = OUT + "/state-main.json";

(async () => {
  const { browser, context, page, logs } = await open({ width: 390, height: 844, scheme: "dark", state: STATE, dpr: 2, video: true, tag: "06-pack" });
  await page.goto(BASE + "/#/town");
  await page.getByTestId("town-screen").waitFor({ timeout: 20000 });
  await page.waitForLoadState("networkidle");
  await page.getByTestId("nav-outfit").tap();
  await page.getByTestId("outfit-screen").waitFor();
  await sleep(500);
  await page.getByTestId("outfit-traps").getByRole("button", { name: "Add Spike Pit" }).tap();
  await page.getByTestId("outfit-traps").getByRole("button", { name: "Add Spike Pit" }).tap();
  const opts = await page.getByTestId("outfit-fence-tier").locator("option").allTextContents();
  console.log("fence options", opts);
  await page.getByTestId("outfit-fence-tier").selectOption({ index: 1 });
  await sleep(300);
  console.log("count value after tier", await page.getByTestId("outfit-fence-count").inputValue());
  await page.getByTestId("outfit-fence-count").scrollIntoViewIfNeeded();
  await snap(page, "06-outfit-fence");
  await page.getByTestId("outfit-ride-out").scrollIntoViewIfNeeded();
  await snap(page, "06-outfit-bottom");
  await page.getByTestId("outfit-ride-out").tap();
  await sleep(300);
  await snap(page, "06-ride-confirm");
  await dump(page, "06-ride-confirm");
  const t0 = Date.now();
  await page.getByTestId("outfit-confirm").tap();
  await snap(page, "06-after-confirm-50ms");
  await sleep(2500);
  await page.waitForLoadState("networkidle");
  console.log("after confirm url", page.url(), Date.now() - t0);
  await snap(page, "07-trail-first");
  await panels(page, "07-trail");
  await dump(page, "07-trail");
  await save(context, STATE);
  console.log(logs.filter((l) => !l.includes("WebGL") && !l.includes("GL Driver")).slice(0, 10));
  await context.close();
  await browser.close();
})();
